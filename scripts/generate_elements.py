def build_dataset():
    """Build the complete elements dataset."""
    data = {
        "_version": "2.0.0",
        "_schema": {
            "type": "object",
            "patternProperties": {
                "^[A-Z][a-z]?$": {
                    "type": "object",
                    "properties": {
                        "z": {"type": "integer", "minimum": 1, "maximum": 118},
                        "symbol": {"type": "string"},
                        "name": {"type": "string"},
                        "atomic_mass": {"type": "number"},
                        "period": {"type": "integer", "minimum": 1, "maximum": 7},
                        "group": {"type": "integer", "minimum": 0, "maximum": 18},
                        "block": {"type": "string", "enum": ["s", "p", "d", "f"]},
                        "category": {"type": "string"},
                        "electron_configuration": {"type": "string"},
                        "oxidation_states": {"type": "array", "items": {"type": "integer"}},
                        "covalent_radius": {"type": "number"},
                        "vdw_radius": {"type": "number"},
                        "electronegativity": {"type": "number"},
                        "ionization_energy": {"type": "number"},
                        "electron_affinity": {"type": "number"},
                        "density": {"type": "number"},
                        "melting_point": {"type": "number"},
                        "boiling_point": {"type": "number"},
                        "phase_at_stp": {"type": "string"},
                        "isotopes": {
                            "type": "array",
                            "items": {
                                "type": "object",
                                "properties": {
                                    "mass_number": {"type": "integer"},
                                    "mass": {"type": "number"},
                                    "abundance": {"type": ["number", "null"]}
                                }
                            }
                        }
                    },
                    "required": ["z", "symbol", "name", "atomic_mass", "period", "group",
                                 "block", "category", "electron_configuration",
                                 "covalent_radius", "vdw_radius", "electronegativity",
                                 "ionization_energy", "density", "phase_at_stp"]
                }
            }
        }
    }

    for sym, z, name, mass, period, group, block, cat, config, ox_states, \
        cov_r, vdw_r, en, ie, ea, density, mp, bp, phase, isotopes in ELEMENTS:

        data[sym] = {
            "z": z,
            "symbol": sym,
            "name": name,
            "atomic_mass": mass,
            "period": period,
            "group": group,
            "block": block,
            "category": cat,
            "electron_configuration": config,
            "oxidation_states": list(ox_states),
            "covalent_radius": cov_r,
            "vdw_radius": vdw_r,
            "electronegativity": en,
            "ionization_energy": ie,
            "electron_affinity": ea,
            "density": density,
            "melting_point": mp,
            "boiling_point": bp,
            "phase_at_stp": phase,
            "isotopes": [
                {"mass_number": mn, "mass": em, "abundance": ab / 100.0 if ab is not None else None}
                for mn, em, ab in isotopes
            ],
        }

    return data


